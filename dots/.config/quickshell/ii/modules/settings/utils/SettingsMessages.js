function format(text, values) {
    return text.replace(/%(\d+)/g, function(token, index) {
        return Number(index) <= values.length ? String(values[Number(index) - 1]) : token;
    });
}

function templatePattern(source) {
    return new RegExp("^" + source.split(/(%\d+)/).map(function(part) {
        if (/^%\d+$/.test(part)) return "([\\s\\S]*?)";
        return part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    }).join("") + "$");
}

function translate(value, tr) {
    var text = String(value == null ? "" : value);
    if (!text) return "";
    if (Object.prototype.hasOwnProperty.call(messages, text))
        return tr(messages[text]);
    var direct = tr(text);
    if (direct !== text) return direct;
    for (var i = 0; i < templates.length; ++i) {
        var entry = templates[i];
        var match = text.match(templatePattern(entry.source));
        if (match) return format(tr(entry.key), match.slice(1));
    }
    // Progress strings contain byte counts and speeds; preserve their values.
    return text.replace(" / tamanho desconhecido", tr(" / unknown size"));
}
